// hostFooterBlock is what a managed sandbox host appends to every comment it
// posts: a blank line, a separator line and a known footer line. It is spelled
// out literally so these tests do not depend on the implementation's list.
const hostFooterBlock = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n"

// hostRewritten is body as a host that appends its footer would store it.
func hostRewritten(body string) string {
	return strings.TrimRight(body, "\n") + hostFooterBlock
}

// A managed sandbox host appends its footer to every published comment. The
// round is still the approved blind publication for the head, so it authorizes
// merge work exactly like the unmodified comment does (#3021).
func TestBlindReviewEvidenceAcceptsHostSuffixedApproval(t *testing.T) {
	body := hostRewritten(reviewpub.BlindBody("## Decision\nAPPROVED", "head"))
	got := blindReviewEvidenceFromComments([]github.PRComment{{ID: "host", Body: body}}, 17, "head")
	if got.outcome != retainedReviewApproval || got.payload["gate"] != gateReadyToMerge {
		t.Fatalf("host-suffixed current-head approval must authorize merge work: %+v", got)
	}
}

// A suffixed publication for another head is as stale as a plain one, and a
// stale head still invalidates an approval the helper confirmed earlier.
func TestBlindReviewEvidenceHostSuffixedApprovalIsHeadBound(t *testing.T) {
	now := time.Now()
	comments := []github.PRComment{
		{ID: "stale", Body: hostRewritten(reviewpub.BlindBody("## Decision\nAPPROVED", "old")), CreatedAt: now},
	}
	if got := blindReviewEvidenceFromComments(comments, 17, "new"); got.present {
		t.Fatalf("approval bound to another head must yield no evidence: %+v", got)
	}
}

// Requested changes survive the host's rewrite as actionable feedback, and the
// feedback retained for the implementor is the publication, not the host's
// footer.
func TestBlindReviewEvidenceHostSuffixedChangesRequestedRetainsTrimmedFeedback(t *testing.T) {
	published := reviewpub.BlindBody("## Findings\n- Important: fix the parser.\n## Decision\nCHANGES_REQUESTED", "head")
	got := blindReviewEvidenceFromComments([]github.PRComment{{ID: "host", Body: hostRewritten(published)}}, 17, "head")
	if !got.actionable || got.outcome == retainedReviewApproval {
		t.Fatalf("host-suffixed changes requested must be actionable feedback: %+v", got)
	}
	record, _ := got.payload[blindReviewKey].(map[string]any)
	body, _ := record["body"].(string)
	if body != published {
		t.Fatalf("retained feedback = %q, want the publication without the host footer %q", body, published)
	}
}

// Only one recognised block is tolerated, and only directly after the identity
// line. Anything else is not a blind publication, so it can neither approve nor
// revoke.
func TestBlindReviewEvidenceRejectsEverythingButOneTrailingHostBlock(t *testing.T) {
	approved := reviewpub.BlindBody("## Decision\nAPPROVED", "head")
	approvedBeforeFooterSection := reviewpub.BlindBody("## Findings\nNone.\n## Decision\n**APPROVED**\n## Previous review progress\n- resolved", "head")
	for name, body := range map[string]string{
		"second block":              hostRewritten(hostRewritten(approved)),
		"text before the block":     strings.TrimRight(approved, "\n") + "\nStill reviewing.\n" + hostFooterBlock,
		"footer without separator":  strings.TrimRight(approved, "\n") + "\n\n_Generated by [Claude Code](https://claude.ai/code)_\n",
		"separator after the text":  strings.TrimRight(approved, "\n") + "\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n",
		"unrecognised footer":       strings.TrimRight(approved, "\n") + "\n\n---\n_Generated by Something Else_\n",
		"stale identity afterwards": hostRewritten(approved) + reviewpub.Identity(reviewpub.BlindTriggerKey, "other"),
		"text between trailer and identity": hostRewritten(strings.Replace(approved,
			"<!-- sandman-publication:", "Edited by a host.\n<!-- sandman-publication:", 1)),
		// The stray line must be rejected by the trailer rule itself, not caught by
		// the approval classifier: the report ends with a section that is not
		// Decision, so the line cannot land in the Decision section.
		"text between trailer and identity, last section is not Decision": hostRewritten(strings.Replace(approvedBeforeFooterSection,
			"<!-- sandman-publication:", "Edited by a host.\n<!-- sandman-publication:", 1)),
	} {
		t.Run(name, func(t *testing.T) {
			if got := blindReviewEvidenceFromComments([]github.PRComment{{ID: "host", Body: body}}, 17, "head"); got.present {
				t.Fatalf("%s became blind review evidence: %+v", name, got)
			}
		})
	}
}

// The newest-wins and unusable-newest-revokes rules apply to suffixed
// publications exactly as to plain ones.
func TestBlindReviewEvidenceHostSuffixedPublicationsKeepNewestWins(t *testing.T) {
	now := time.Now()
	comments := []github.PRComment{
		{ID: "old", Body: hostRewritten(reviewpub.BlindBody("## Decision\nAPPROVED", "head")), CreatedAt: now},
		{ID: "new", Body: hostRewritten(reviewpub.BlindBody("## Decision\nCHANGES_REQUESTED", "head")), CreatedAt: now.Add(time.Second)},
	}
	if got := blindReviewEvidenceFromComments(comments, 17, "head"); !got.actionable || got.outcome == retainedReviewApproval {
		t.Fatalf("newer suffixed changes requested must beat the older approval: %+v", got)
	}
	comments = []github.PRComment{
		{ID: "old", Body: hostRewritten(reviewpub.BlindBody("## Decision\nAPPROVED", "head")), CreatedAt: now},
		{ID: "unusable", Body: hostRewritten(reviewpub.BlindBody("No decision supplied.", "head")), CreatedAt: now.Add(time.Second)},
	}
	if got := blindReviewEvidenceFromComments(comments, 17, "head"); got.present || got.outcome == retainedReviewApproval {
		t.Fatalf("newer unusable suffixed publication must revoke the older approval: %+v", got)
	}
}

// A host rewrite never changes how a captured approving report classifies.
func TestBlindReviewEvidenceHostSuffixDoesNotChangeCorpusClassification(t *testing.T) {
	for name, report := range capturedApprovingReports(t) {
		t.Run(name, func(t *testing.T) {
			plain := reviewpub.BlindBody(reviewpub.StripMarkers(report), "head")
			want := blindReviewEvidenceFromComments([]github.PRComment{{ID: "plain", Body: plain}}, 17, "head")
			got := blindReviewEvidenceFromComments([]github.PRComment{{ID: "plain", Body: hostRewritten(plain)}}, 17, "head")
			if got.present != want.present || got.outcome != want.outcome || got.actionable != want.actionable ||
				got.payload["gate"] != want.payload["gate"] {
				t.Fatalf("host-suffixed classification = %+v, plain = %+v", got, want)
			}
		})
	}
}

// A configured review command ignores blind publications entirely, including
// the ones a host rewrote: a suffixed blind publication is not a response to a
// delegated request, so it never reaches the classification sources. The test
// observes that exclusion directly (no top-level response is counted) and
// carries a positive control, so it fails if the tolerance is removed from the
// blind predicate or if the setup stops observing responses at all.
func TestConfiguredReviewIgnoresHostSuffixedBlindPublication(t *testing.T) {
	now := time.Now().UTC()
	s := &runSession{deps: runDeps{githubClient: &registrationGitHubClient{}},
		renderCfg: prompt.RenderConfig{ReviewCommand: "/sandman review", ReviewCommandSet: true}}
	request := reviewRequestEnvelope{
		TriggerID: "missing-trigger", TriggerPrefix: "/sandman review", HeadSHA: "head",
		TriggerCreatedAt:    now.Add(-time.Minute).Format(time.RFC3339Nano),
		DeadlineUnixSeconds: int(now.Add(time.Minute).Unix()),
	}
	observe := func(body string) *reviewTimeoutHandoff {
		t.Helper()
		handoff, err := s.observeCurrentReviewEvidence(context.Background(), request,
			&github.PR{Number: 17, HeadRefOid: "head"}, []github.PRComment{{ID: "c1", Body: body, CreatedAt: now}})
		if err != nil {
			t.Fatal(err)
		}
		return handoff
	}
	control := observe("## Decision\nAPPROVED")
	if control == nil || control.ResponseCounts.TopLevel != 1 ||
		len(control.Classification.reviewDecisionApprovalEvidenceFor(request, "")) != 1 {
		t.Fatalf("positive control: a delegated approval must be observed as a response and as approval evidence: %+v", control)
	}
	for _, verdict := range []string{"APPROVED", "CHANGES_REQUESTED"} {
		published := reviewpub.BlindBody("## Decision\n"+verdict, "head")
		for name, body := range map[string]string{"plain": published, "host-suffixed": hostRewritten(published)} {
			if handoff := observe(body); handoff != nil && handoff.ResponseCounts.TopLevel != 0 {
				t.Fatalf("%s blind %s became a delegated response: %+v", name, verdict, handoff.ResponseCounts)
			}
		}
	}
}
