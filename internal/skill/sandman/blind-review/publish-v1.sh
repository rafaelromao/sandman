#!/bin/sh
# GitHub calls: pr view --json state,headRefOid; pr comment --body-file;
# pr view --json state,headRefOid,comments. When GraphQL is unavailable (see
# github-v1.sh) the same reads and the post use REST instead. A failed mutation
# is never retried, and never replaced by a post through the other route.
set -eu
# Footer lines a managed sandbox host is known to append to published comments
# (JSON array); the Go side keeps the same closed list.
host_footers='["_Generated by [Claude Code](https://claude.ai/code)_"]'
repository='' pull_request='' head='' decision='' print_body=false
refuse() {
  jq -cn --arg reason "$1" '{protocol:"blind-review/v1",state:"refused",reason:$reason}' >&2
  exit 1
}
while [ "$#" -gt 0 ]; do
  case "$1" in
    --repository) repository=$2; shift 2 ;;
    --pull-request) pull_request=$2; shift 2 ;;
    --head-sha) head=$2; shift 2 ;;
    --decision-file) decision=$2; shift 2 ;;
    --print-body) print_body=true; shift ;;
    *) refuse invalid-argument ;;
  esac
done
[ -n "$head" ] && [ -f "$decision" ] || refuse invalid-input
head=$(printf '%s' "$head" | jq -Rr 'gsub("^\\s+|\\s+$"; "") | ascii_downcase')
if command -v sha256sum >/dev/null 2>&1; then
  digest=$(printf 'blind-review\000%s' "$head" | sha256sum) || refuse checksum-failed
elif command -v shasum >/dev/null 2>&1; then
  digest=$(printf 'blind-review\000%s' "$head" | shasum -a 256) || refuse checksum-failed
else
  refuse checksum-unavailable
fi
identity=${digest%% *}
[ "${#identity}" -eq 64 ] || refuse checksum-invalid
case "$identity" in *[!0-9a-f]*) refuse checksum-invalid ;; esac
helper_dir=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
if [ "$print_body" = true ]; then
  exec jq -Rrjs --arg identity "$identity" -f "$helper_dir/publication-v1.jq" "$decision"
fi
[ -n "$repository" ] && [ -n "$pull_request" ] || refuse invalid-input
# shellcheck source=github-v1.sh
. "$helper_dir/github-v1.sh"
gh_mode=graphql # github-v1.sh switches it to rest only when GraphQL is unavailable
tmp=$(mktemp -d "${TMPDIR:-/tmp}/sandman-blind-publication.XXXXXX")
trap 'rm -f "$tmp"/*; rmdir "$tmp"' EXIT HUP INT TERM
if ! gh pr view "$pull_request" --repo "$repository" --json state,headRefOid >"$tmp/pr"; then
  gh_select_rest || refuse lookup-failed
  gh_rest_pr "$repository" "$pull_request" "$tmp/pr" "$tmp" || refuse lookup-failed
fi
jq -e --arg head "$head" '
  (.state | ascii_downcase) == "open" and (.headRefOid | ascii_downcase) == $head
' "$tmp/pr" >/dev/null || refuse stale-or-closed
jq -Rrjs --arg identity "$identity" -f "$helper_dir/publication-v1.jq" "$decision" >"$tmp/body" ||
  refuse invalid-decision
posted_id=''
if [ "$gh_mode" = rest ]; then
  gh_rest_post_comment "$repository" "$pull_request" "$tmp/body" "$tmp/posted" ||
    refuse publication-uncertain
  posted_url=$(jq -r '.html_url // empty' "$tmp/posted") || refuse publication-uncertain
  posted_id=$(jq -r '.id // empty | tostring' "$tmp/posted") || refuse publication-uncertain
  [ -n "$posted_url" ] && [ -n "$posted_id" ] || refuse publication-uncertain
else
  posted_url=$(gh pr comment "$pull_request" --repo "$repository" --body-file "$tmp/body") ||
    refuse publication-uncertain
fi
if [ "$gh_mode" = rest ]; then
  gh_rest_pr_with_comments "$repository" "$pull_request" "$tmp/pr" "$tmp" ||
    refuse confirmation-unavailable
else
  gh pr view "$pull_request" --repo "$repository" --json state,headRefOid,comments >"$tmp/pr" ||
    refuse confirmation-unavailable
fi
jq -ce --arg repository "$repository" --argjson pull_request "$pull_request" \
  --arg head "$head" --arg url "$posted_url" --arg posted_id "$posted_id" \
  --rawfile body "$tmp/body" --argjson footers "$host_footers" '
  # A managed sandbox host may append one recognised footer block to a comment
  # it publishes. The live body must be the intended body, or the intended body
  # (trailing whitespace ignored) followed by newlines only (at least two, so a
  # blank line precedes the rule), "---", a newline and one known footer line.
  # The host appends to the untrimmed body, so the final newline of the intended
  # body counts among those newlines, and a host that drops the trailing newline
  # of the footer is accepted too. Nothing else is tolerated, so the block
  # cannot carry text, a verdict or an identity.
  def rtrim: sub("[ \\t\\r\\n]+$"; "");
  def block($rest; $footer):
    ("---\n" + $footer) as $tail |
    ($rest | endswith($tail)) and
    (($rest | length) - ($tail | length)) as $gap |
    $gap >= 2 and ($rest[0:$gap] | test("^\\n+$"));
  def published($live; $intended):
    $live == $intended or
    (($live | rtrim) as $trimmed |
     ($intended | rtrim) as $base |
     ($trimmed | startswith($base)) and
     ($trimmed[($base | length):]) as $rest |
     any($footers[]; block($rest; .)));
  select((.state | ascii_downcase) == "open" and (.headRefOid | ascii_downcase) == $head) |
  # The posted comment is identified by the id the REST post returned, or by the
  # URL the GraphQL-backed post printed; exactly one live comment must match.
  def posted: if $posted_id != "" then ((.id | tostring) == $posted_id) else .url == $url end;
  [.comments[] | select(posted and published(.body; $body) and (.createdAt | type == "string"))] |
  select(length == 1) | .[0] |
  {protocol:"blind-review/v1",state:"confirmed",repository:$repository,pull_request:$pull_request,
   head_sha:$head,comment_url:.url,created_at:.createdAt,
   verdict: (if ($body | split("\n") | map(select(test("\\S"))) | .[-2]) == "<!-- sandman-verdict:approved -->" then "approved"
     elif ($body | split("\n") | map(select(test("\\S"))) | .[-2]) == "<!-- sandman-verdict:changes_requested -->" then "changes_requested"
     else "unknown" end)}
' "$tmp/pr" || refuse confirmation-uncertain
