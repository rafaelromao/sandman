// hostBlock is what a managed sandbox host appends to a comment it posts. It is
// spelled out literally so the table does not depend on the recognised list.
const (
	hostFooterLine = "_Generated by [Claude Code](https://claude.ai/code)_"
	hostBlock      = "\n\n---\n" + hostFooterLine + "\n"
)

func TestTrimHostSuffixRemovesExactlyOneTrailingBlock(t *testing.T) {
	published := BlindBody("## Decision\nAPPROVED", "head")
	core := strings.TrimRight(published, "\n")
	for name, tc := range map[string]struct {
		body string
		want string
		ok   bool
	}{
		"canonical body is unchanged":     {published, published, false},
		"one block":                       {core + hostBlock, published, true},
		"one block without final newline": {core + strings.TrimRight(hostBlock, "\n"), published, true},
		"extra trailing blank lines":      {core + hostBlock + "\n\n  \n", published, true},
		"extra blank lines before":        {core + "\n\n\n" + strings.TrimLeft(hostBlock, "\n"), published, true},
		"CRLF line endings":               {strings.ReplaceAll(core+hostBlock, "\n", "\r\n"), published, true},
		"padded separator and footer":     {core + "\n\n  ---  \n  " + hostFooterLine + "  \n", published, true},
		"footer block only":               {hostBlock, "", true},
		"second block leaves one":         {core + hostBlock + hostBlock, core + hostBlock, true},
		"text after the block":            {core + hostBlock + "more\n", core + hostBlock + "more\n", false},
		"footer without separator":        {core + "\n\n" + hostFooterLine + "\n", core + "\n\n" + hostFooterLine + "\n", false},
		"separator without blank line":    {core + "\n---\n" + hostFooterLine + "\n", core + "\n---\n" + hostFooterLine + "\n", false},
		"blank line between rule+footer":  {core + "\n\n---\n\n" + hostFooterLine + "\n", core + "\n\n---\n\n" + hostFooterLine + "\n", false},
		"unknown footer":                  {core + "\n\n---\n_Generated by Something Else_\n", core + "\n\n---\n_Generated by Something Else_\n", false},
		"empty body":                      {"", "", false},
	} {
		t.Run(name, func(t *testing.T) {
			got, ok := TrimHostSuffix(tc.body)
			if got != tc.want || ok != tc.ok {
				t.Fatalf("TrimHostSuffix(%q) = (%q, %t), want (%q, %t)", tc.body, got, ok, tc.want, tc.ok)
			}
		})
	}
}

// The tolerance law: AnswersBlind and PublishedVerdict are the strict
// predicates evaluated on what remains once exactly one recognised block is
// removed. Each row names the expected outcome of both.
func TestHostSuffixPredicateOutcomes(t *testing.T) {
	const head = "head"
	approved := BlindBody("## Decision\nAPPROVED", head)
	changes := BlindBody("## Decision\nCHANGES_REQUESTED", head)
	core := strings.TrimRight(approved, "\n")
	verdictOnly := Marker(Approved) + "\n"
	for name, tc := range map[string]struct {
		body      string
		answers   bool
		verdict   Verdict
		published bool
	}{
		"canonical":                       {approved, true, Approved, true},
		"canonical changes requested":     {changes, true, ChangesRequested, true},
		"one block":                       {core + hostBlock, true, Approved, true},
		"one block, changes requested":    {strings.TrimRight(changes, "\n") + hostBlock, true, ChangesRequested, true},
		"one block without final newline": {core + strings.TrimRight(hostBlock, "\n"), true, Approved, true},
		"one block with CRLF":             {strings.ReplaceAll(core+hostBlock, "\n", "\r\n"), true, Approved, true},
		"extra blank lines around block":  {core + "\n\n\n\n---\n" + hostFooterLine + "\n\n\n", true, Approved, true},
		"two blocks":                      {core + hostBlock + hostBlock, false, Unknown, false},
		"text between identity and block": {core + "\nStill reviewing.\n" + hostBlock, false, Unknown, false},
		"footer block only":               {hostBlock, false, Unknown, false},
		"footer without separator":        {core + "\n\n" + hostFooterLine + "\n", false, Unknown, false},
		"separator without blank line":    {core + "\n---\n" + hostFooterLine + "\n", false, Unknown, false},
		"unknown footer":                  {core + "\n\n---\n_Generated by Something Else_\n", false, Unknown, false},
		"another head":                    {strings.TrimRight(BlindBody("## Decision\nAPPROVED", "other"), "\n") + hostBlock, false, Approved, true},
		"another trigger key": {strings.TrimRight(Body("## Decision\nAPPROVED", "request", head), "\n") + hostBlock,
			false, Approved, true},
		// A footer cannot carry a verdict: the trailer must be directly before
		// the identity, and it is judged on the publication, not on the block.
		"verdict only in the footer region": {strings.TrimRight(Identity(BlindTriggerKey, head), "\n") + "\n\n---\n" + hostFooterLine + "\n" + verdictOnly, false, Unknown, false},
		// The block is not last, so nothing is trimmed: the final (stale) identity
		// binds the body, and the verdict is the strict Decision-token fallback.
		"stale identity after the block": {core + hostBlock + Identity(BlindTriggerKey, "other"), false, Approved, true},
		// The strict rule is unchanged when no block is present.
		"text between trailer and identity": {"## Decision\nAPPROVED\n" + Marker(Approved) + "\nnote\n" + Identity(BlindTriggerKey, head), true, Approved, true},
	} {
		t.Run(name, func(t *testing.T) {
			if got := AnswersBlind(tc.body, head); got != tc.answers {
				t.Errorf("AnswersBlind = %t, want %t", got, tc.answers)
			}
			verdict, published := PublishedVerdict(tc.body)
			if verdict != tc.verdict || published != tc.published {
				t.Errorf("PublishedVerdict = (%q, %t), want (%q, %t)", verdict, published, tc.verdict, tc.published)
			}
		})
	}
}

// Published stays strict: the delegated-review gates that call it keep their
// evidence rules, so a host-footer-suffixed publication is not "Published".
func TestPublishedStaysStrictForHostSuffixedBodies(t *testing.T) {
	body := strings.TrimRight(Body("## Decision\nAPPROVED", "request", "head"), "\n")
	if !Published(body + "\n") {
		t.Fatal("a canonical publication must be Published")
	}
	if Published(body + hostBlock) {
		t.Fatal("a host-suffixed body must not be Published: delegated gates stay byte-identical")
	}
	if verdict, published := PublishedVerdictExact(body + hostBlock); published || verdict != Unknown {
		t.Fatalf("PublishedVerdictExact tolerated a host footer: (%q, %t)", verdict, published)
	}
	if verdict, published := PublishedVerdict(body + hostBlock); !published || verdict != Approved {
		t.Fatalf("PublishedVerdict must tolerate exactly one host footer: (%q, %t)", verdict, published)
	}
}

// The closed list is data: every recognised footer is returned for the helper
// parity test, and a caller cannot mutate the list through the copy.
func TestHostFootersReturnsAnImmutableCopy(t *testing.T) {
	footers := HostFooters()
	if len(footers) == 0 {
		t.Fatal("no recognised host footer")
	}
	footers[0] = "tampered"
	if got := HostFooters(); got[0] == "tampered" {
		t.Fatal("HostFooters exposes the internal list")
	}
	for _, footer := range HostFooters() {
		if _, ok := TrimHostSuffix("body\n\n---\n" + footer + "\n"); !ok {
			t.Errorf("listed footer %q is not recognised", footer)
		}
	}
}
