package reviewpub

import (
	"os"
	"strings"
	"testing"
)

const (
	liveHostFooter = "_Generated by [Claude Code](https://claude.ai/code)_"
	liveHostBlock  = "\n\n---\n" + liveHostFooter + "\n"
)

// hostRows are the live bodies a host may return for the posted blind
// publication of "## Decision\nAPPROVED" at head "abc". helper is whether the
// publication helper confirms the round (it needs the intended body plus at
// most one recognised block, byte for byte); go is whether the Go predicates
// accept the body as an approving blind publication. The helper may be
// stricter than Go (CRLF), never looser: helper implies go.
func hostRows() []struct {
	name, body  string
	helper, go_ bool
} {
	intended := BlindBody("## Decision\nAPPROVED", "abc")
	core := strings.TrimRight(intended, "\n")
	other := BlindBody("## Decision\nAPPROVED", "other")
	changes := BlindBody("## Decision\nCHANGES_REQUESTED", "abc")
	altered := strings.Replace(intended, "sandman-verdict:approved", "sandman-verdict:changes_requested", 1)
	return []struct {
		name, body  string
		helper, go_ bool
	}{
		{"unmodified", intended, true, true},
		{"one block", core + liveHostBlock, true, true},
		{"one block, no final newline", core + strings.TrimRight(liveHostBlock, "\n"), true, true},
		{"one block after the final newline", intended + strings.TrimLeft(liveHostBlock, "\n"), false, false},
		{"one block, CRLF", strings.ReplaceAll(core+liveHostBlock, "\n", "\r\n"), false, true},
		{"second block", core + liveHostBlock + liveHostBlock, false, false},
		{"text between identity and block", core + "\nEdited by a host.\n" + liveHostBlock, false, false},
		{"text before the trailer", "Edited by a host.\n" + intended, false, true},
		{"text between trailer and identity", strings.Replace(intended, "<!-- sandman-publication:", "extra\n<!-- sandman-publication:", 1), false, true},
		{"unknown footer", core + "\n\n---\n_Generated by Something Else_\n", false, false},
		{"footer without separator", core + "\n\n" + liveHostFooter + "\n", false, false},
		{"separator without blank line", core + "\n---\n" + liveHostFooter + "\n", false, false},
		{"another head", strings.TrimRight(other, "\n") + liveHostBlock, false, false},
		{"altered verdict", strings.TrimRight(altered, "\n") + liveHostBlock, false, false},
		{"different publication", strings.TrimRight(changes, "\n") + liveHostBlock, false, false},
	}
}

// A managed sandbox host appends one footer block to the posted comment. The
// helper still posts exactly once and confirms that comment; every other
// difference stays confirmation-uncertain and never posts a replacement.
func TestBlindPublicationConfirmsUnderHostFooterTolerance(t *testing.T) {
	for _, row := range hostRows() {
		t.Run(row.name, func(t *testing.T) {
			live := row.body
			run := runPublishHelper(t, &live)
			if run.mutations != 1 {
				t.Fatalf("a round must post exactly once, posted %d times", run.mutations)
			}
			if row.helper {
				if run.err != nil {
					t.Fatalf("helper refused a tolerated body: %v\nstderr=%s", run.err, run.stderr)
				}
				envelope := run.envelope(t)
				if envelope["state"] != "confirmed" || envelope["verdict"] != "approved" || envelope["head_sha"] != "abc" ||
					envelope["comment_url"] != "https://example.test/comment/1" {
					t.Fatalf("unexpected envelope: %v", envelope)
				}
			} else {
				if run.err == nil {
					t.Fatalf("helper confirmed an untolerated body: %s", run.stdout)
				}
				if refusal := run.refusal(t); refusal["state"] != "refused" || refusal["reason"] != "confirmation-uncertain" {
					t.Fatalf("unexpected refusal: %v", refusal)
				}
			}
			// The Go predicates agree with the table, and the helper is never
			// looser than they are.
			verdict, published := PublishedVerdict(live)
			goAccepts := AnswersBlind(live, "abc") && published && verdict == Approved
			if goAccepts != row.go_ {
				t.Errorf("Go predicates accept = %t, want %t", goAccepts, row.go_)
			}
			if row.helper && !goAccepts {
				t.Error("the helper confirmed a body the Go predicates reject")
			}
		})
	}
}

// The helper's footer list is the Go list, so the two tolerances cannot drift.
func TestBlindPublicationHelperFooterListMatchesGo(t *testing.T) {
	helper, err := os.ReadFile("../skill/sandman/blind-review/publish-v1.sh")
	if err != nil {
		t.Fatal(err)
	}
	for _, footer := range HostFooters() {
		if !strings.Contains(string(helper), footer) {
			t.Errorf("publish-v1.sh does not list the recognised host footer %q", footer)
		}
	}
}
