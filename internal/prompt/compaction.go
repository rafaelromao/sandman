package prompt

import (
	"fmt"
	"strconv"
	"strings"
	"unicode/utf8"
)

// TaskHistoryHeading names the Sandman-owned section that points a compacted
// Task at the archive holding its earlier content.
const TaskHistoryHeading = "## Sandman Task History"

// taskHistoryEnd closes the history pointer, so text an agent writes after it
// stays its own and is never replaced with the pointer.
const taskHistoryEnd = "<!-- end of Sandman Task History -->"

// nextStepHeading is the template section the agent rewrites with its current
// position. Its beginning is kept when it grows; see nextStepLimit.
const nextStepHeading = "## Next Step"

// nextStepLimit caps the Next Step group of a compacted Task.
const nextStepLimit = 4 * 1024

// runtimeHeadings are the sections Sandman composes or rewrites at launches,
// including both Runtime Context headings it updates (see
// holdsRuntimeContext), so compaction always keeps them.
var runtimeHeadings = map[string]bool{
	runtimeContextHeading:             true,
	reviewTimeoutContextHeading:       true,
	reviewEvidenceHeading:             true,
	continuationFreshnessGuardHeading: true,
	contextRecoveryGuardHeading:       true,
	ciOwnershipContextHeading:         true,
	managedHandoffContextHeading:      true,
	TaskHistoryHeading:                true,
}

// TaskCompaction configures CompactTask.
type TaskCompaction struct {
	// Threshold is the size in bytes above which the Task is compacted.
	Threshold int
	// Target is the size in bytes compaction aims for.
	Target int
	// Force compacts even when the Task is not above Threshold.
	Force bool
	// ArchivePath is the worktree-relative path the history pointer names.
	ArchivePath string
	// Bounds locates the Task's structure (see MarkedTaskBounds and
	// BuiltInTaskBounds); nil leaves the Task alone.
	Bounds *TaskBounds
}

// TaskCompactionResult reports what CompactTask did.
type TaskCompactionResult struct {
	Content       string
	Compacted     bool
	Before, After int
	Moved         []string
	// ArchivePath is the archive the history pointer names, when compacted.
	ArchivePath string
	// Reason says why a Task that qualified for compaction was left alone.
	Reason string
}

type taskSection struct {
	heading string // trimmed heading line; empty for the preamble
	text    string
	// afterPointer marks text an agent wrote after a history pointer's end
	// marker, before the next heading.
	afterPointer     bool
	generatedPointer bool
}

// label names a section in the history pointer's list of moved sections.
func (s taskSection) label() string {
	if s.afterPointer {
		return "## Notes after the previous Sandman Task History"
	}
	return s.heading
}

// splitAtPointerEnd separates text written after a history pointer's end
// marker from the pointer, so compaction replaces only the generated bytes.
func splitAtPointerEnd(sections []taskSection) []taskSection {
	var out []taskSection
	for _, section := range sections {
		if section.heading == TaskHistoryHeading {
			// An agent's editor may have rewritten the line endings.
			if _, end := findLine(section.text, taskHistoryEnd); end >= 0 &&
				strings.HasPrefix(strings.ReplaceAll(section.text, "\r\n", "\n"), TaskHistoryHeading+"\n\nSandman moved ") {
				section.generatedPointer = true
				if tail := section.text[end:]; strings.TrimSpace(tail) != "" {
					section.text = section.text[:end]
					out = append(out, section, taskSection{text: tail, afterPointer: true})
					continue
				}
			}
		}
		out = append(out, section)
	}
	return out
}

// splitTaskSections splits a Task at its H2 headings outside fenced code
// blocks. Text before the first heading is the preamble section.
func splitTaskSections(content string) []taskSection {
	return splitTaskSectionsFrom(content, 0)
}

// splitTaskSectionsFrom splits content from the line starting at byte offset
// from. Code blocks are read over the whole content, so a block that crosses
// from stays in the preamble and its lines are never headings.
func splitTaskSectionsFrom(content string, from int) []taskSection {
	lines := strings.SplitAfter(content, "\n")
	fenced := fencedLines(lines)
	first := lineAt(lines, from)
	headings := []string{""}
	starts := []int{first}
	for i := first; i < len(lines); i++ {
		if heading, ok := h2Heading(lines[i]); ok && !fenced[i] {
			headings = append(headings, heading)
			starts = append(starts, i)
		}
	}
	sections := make([]taskSection, len(starts))
	for n, start := range starts {
		end := len(lines)
		if n+1 < len(starts) {
			end = starts[n+1]
		}
		sections[n] = taskSection{heading: headings[n], text: strings.Join(lines[start:end], "")}
	}
	return sections
}

// h2Heading reports whether a line is an H2, which Markdown allows to be
// indented by up to three spaces, and returns it as "## title".
func h2Heading(line string) (string, bool) {
	line = strings.TrimRight(line, "\r\n")
	body := strings.TrimLeft(line, " ")
	if len(line)-len(body) > 3 || body != "##" && !strings.HasPrefix(body, "## ") && !strings.HasPrefix(body, "##\t") {
		return "", false
	}
	return strings.TrimSpace("## " + strings.TrimSpace(body[2:])), true
}

// lineAt returns the index of the first line starting at or after byte offset.
func lineAt(lines []string, offset int) int {
	i := 0
	for start := 0; i < len(lines) && start < offset; i++ {
		start += len(lines[i])
	}
	return i
}

// inCodeBlock reports whether the line at byte offset belongs to a fenced
// code block.
func inCodeBlock(content string, offset int) bool {
	lines := strings.SplitAfter(content, "\n")
	i := lineAt(lines, offset)
	return i < len(lines) && fencedLines(lines)[i]
}

// fencedLines reports which lines belong to a fenced code block, delimiters
// included. A fence with no closer (a truncated log, say) is read as text, so
// it cannot swallow the headings after it.
func fencedLines(lines []string) []bool {
	fences := make([]fence, len(lines))
	for i, line := range lines {
		fences[i], _ = parseFence(strings.TrimRight(line, "\r\n"))
	}
	// closable[i] reports whether a later line closes a block opened at i.
	closable := make([]bool, len(lines))
	longest := map[byte]int{} // the longest bare fence further down
	for i := len(lines) - 1; i >= 0; i-- {
		if f := fences[i]; f.char != 0 {
			closable[i] = longest[f.char] >= f.length
			if !f.info {
				longest[f.char] = max(longest[f.char], f.length)
			}
		}
	}
	fenced := make([]bool, len(lines))
	var open fence
	for i, f := range fences {
		switch {
		case open.char != 0:
			fenced[i] = true
			if f.closes(open) {
				open = fence{}
			}
		case closable[i]:
			open, fenced[i] = f, true
		}
	}
	return fenced
}

// fence is a fenced code block delimiter: its character and length, and
// whether an info string follows it.
type fence struct {
	char   byte
	length int
	info   bool
}

// parseFence recognises a fence line, indented by at most three spaces.
func parseFence(line string) (fence, bool) {
	trimmed := strings.TrimLeft(line, " ")
	if len(line)-len(trimmed) > 3 || len(trimmed) < 3 || trimmed[0] != '`' && trimmed[0] != '~' {
		return fence{}, false
	}
	char := trimmed[0]
	length := 0
	for length < len(trimmed) && trimmed[length] == char {
		length++
	}
	rest := trimmed[length:]
	if length < 3 || char == '`' && strings.Contains(rest, "`") {
		return fence{}, false
	}
	return fence{char: char, length: length, info: strings.TrimSpace(rest) != ""}, true
}

// closes reports whether f ends the block open started: the same character,
// at least as long, and no info string.
func (f fence) closes(open fence) bool {
	return f.char == open.char && f.length >= open.length && !f.info
}

// isProtectedHeading reports whether a section holds agent state that is
// never moved: the checklist, a plan or a status line.
func isProtectedHeading(heading string) bool {
	if heading == "## Execution Checklist" {
		return true
	}
	if strings.HasPrefix(heading, "## Status:") {
		return true
	}
	return heading == "## Plan" || strings.HasPrefix(heading, "## Plan ") || strings.HasPrefix(heading, "## Plan:")
}

// holdsRuntimeContext reports whether any line is one a continuation takes for
// a Runtime Context heading, in a code block or not: the review settings may be
// written below it.
func holdsRuntimeContext(text string) bool {
	for line := range strings.SplitSeq(text, "\n") {
		switch strings.TrimSpace(line) {
		case reviewTimeoutContextHeading, runtimeContextHeading:
			return true
		}
	}
	return false
}

// isKeptSection reports whether compaction keeps a section byte for byte
// wherever it is: Sandman's sections, protected state, text a continuation may
// write the review settings into, and text whose fenced block swallowed one of
// those, including a note without a heading of its own.
func isKeptSection(section taskSection, topLevel map[string]bool) bool {
	body := section.text
	if section.heading != "" {
		_, body, _ = strings.Cut(body, "\n")
	}
	return runtimeHeadings[section.heading] || isProtectedHeading(section.heading) ||
		holdsRuntimeContext(section.text) || swallowsProtected(body, topLevel)
}

// CompactTask moves the oldest agent-written history out of an oversized Task
// and trims its Next Step group to the first 4 KiB, using opts.Bounds. The
// rest of the structure, plans, status lines and Sandman's sections are kept
// byte for byte; history is kept from the end while the Task fits the target.
// The caller archives the original before using the result.
func CompactTask(content string, opts TaskCompaction) TaskCompactionResult {
	result := TaskCompactionResult{Content: content, Before: len(content), After: len(content)}
	if opts.Target <= 0 || !opts.Force && (opts.Threshold <= 0 || len(content) <= opts.Threshold) {
		return result
	}
	if opts.Bounds == nil {
		result.Reason = "no recorded Task structure"
		return result
	}
	bounds := *opts.Bounds
	topLevel := map[string]bool{}
	for _, section := range splitTaskSections(content) {
		topLevel[section.heading] = true
	}
	// A Next Step whose bounds fall inside a code block is not capped: cutting
	// there would split the block.
	from, to := bounds.NextStepStart, bounds.NextStepEnd
	if inCodeBlock(content, from) || inCodeBlock(content, to) {
		from, to = 0, 0
	}
	head, moved, changed := capNextStep(content[:bounds.StructureEnd], from, to, topLevel)

	// What follows the structure is history, except what is always kept. The
	// text before the first heading stays with the structure, and the pointer
	// goes right after it, so text the agent appends later never becomes part
	// of the pointer.
	tail := splitAtPointerEnd(splitTaskSectionsFrom(content, bounds.StructureEnd))
	prefix, rest := head, 0
	if len(tail) > 0 && tail[0].heading == "" && !tail[0].afterPointer {
		prefix, rest = head+tail[0].text, 1
	}
	separator := blankLineAfter(prefix)
	kept := make([]string, len(tail))
	var history []int
	fixed := len(head)
	for i, section := range tail {
		switch {
		case section.generatedPointer:
			continue
		case section.heading == "" && !section.afterPointer, isKeptSection(section, topLevel):
			kept[i] = section.text
			fixed += len(section.text)
		default:
			history = append(history, i)
		}
	}

	// Move the fewest oldest history sections for the Task, with the pointer
	// naming exactly what moves, to fit the target; if none fits, move all.
	keepFrom := len(history)
	keptSize := fixed + historyBytes(tail, history)
	listedBytes := 0
	for _, heading := range moved {
		listedBytes += len("- \n") + len(strings.TrimPrefix(heading, "## "))
	}
	basePointerSize := len(renderHistoryPointer(opts, 0, nil)) - 1 + len(separator)
	for n := 0; n <= len(history); n++ {
		if n > 0 {
			section := tail[history[n-1]]
			keptSize -= len(section.text)
			listedBytes += len("- \n") + len(strings.TrimPrefix(section.label(), "## "))
		}
		if n == 0 && !changed {
			if len(content) <= opts.Target {
				keepFrom = 0
				break
			}
			continue
		}
		pointerSize := basePointerSize + len(strconv.Itoa(len(content)-keptSize))
		count := len(moved) + n
		if count > 0 {
			pointerSize += len(movedSectionsHeading) + listedBytes
		}
		if keptSize+pointerSize <= opts.Target {
			keepFrom = n
			break
		}
	}
	for _, i := range history[keepFrom:] {
		kept[i] = tail[i].text
	}
	for _, i := range history[:keepFrom] {
		moved = append(moved, tail[i].label())
	}

	if keepFrom == 0 && !changed {
		if len(content) <= opts.Target {
			result.Reason = "already compact"
		} else {
			result.Reason = "protected content exceeds the target"
		}
		return result
	}

	var b strings.Builder
	b.WriteString(prefix + separator)
	b.WriteString(renderHistoryPointer(opts, len(content)-keptSize, moved))
	for _, text := range kept[rest:] {
		b.WriteString(text)
	}
	compacted := b.String()
	if len(compacted) >= len(content) {
		result.Reason = "protected content exceeds the target, and moving the rest would not shrink the Task"
		return result
	}
	result.Content, result.Compacted, result.After, result.Moved = compacted, true, len(compacted), moved
	result.ArchivePath = opts.ArchivePath
	return result
}

// blankLineAfter returns the newlines that put a blank line after text. It
// only adds: no byte of what precedes the pointer is ever removed.
func blankLineAfter(text string) string {
	switch {
	case strings.HasSuffix(text, "\n\n"), strings.HasSuffix(text, "\n\r\n"):
		return ""
	case strings.HasSuffix(text, "\n"):
		return "\n"
	}
	return "\n\n"
}

// capNextStep keeps the first 4 KiB of the Next Step group of a Task's
// structure, the bytes from from to to. Once cut, what follows in the group
// moves too: the group keeps a prefix, never fragments from beyond the limit.
// Kept sections inside it stay and do not count.
func capNextStep(structure string, from, to int, topLevel map[string]bool) (string, []string, bool) {
	if from >= to {
		return structure, nil, false
	}
	sections := splitTaskSections(structure[from:to])
	size := 0
	for _, section := range sections {
		if !isKeptSection(section, topLevel) {
			size += len(section.text)
		}
	}
	if size <= nextStepLimit {
		return structure, nil, false
	}
	var b strings.Builder
	var moved []string
	// The cut ends with a blank line, which counts against the limit.
	room := nextStepLimit - len("\n\n")
	cut := false
	for _, section := range sections {
		switch {
		case section.text == "":
		case isKeptSection(section, topLevel):
			b.WriteString(section.text)
		case !cut && len(section.text) <= room:
			b.WriteString(section.text)
			room -= len(section.text)
		case !cut && room > len(section.heading):
			prefix := cutOutsideFence(section.text, room)
			if nextStepLimit-room+len(prefix) < nextStepLimit/2 {
				// A long line or code block would waste most of the limit.
				prefix = cutInside(section.text, room)
			}
			b.WriteString(trimTrailingNewlines(prefix) + "\n\n")
			cut = true
			moved = append(moved, fmt.Sprintf("%s (beyond the first %d KiB)", section.label(), nextStepLimit/1024))
		default:
			cut = true
			moved = append(moved, section.label())
		}
	}
	return structure[:from] + b.String() + structure[to:], moved, true
}

func historyBytes(sections []taskSection, indexes []int) int {
	n := 0
	for _, i := range indexes {
		n += len(sections[i].text)
	}
	return n
}

// swallowsProtected reports whether body holds, inside a fenced block, a
// heading compaction would keep, typically because an agent left a fence open
// and a later one closed it. Such a section is kept whole. Only a clearly
// bounded example is not: a language-tagged block whose first line is the
// heading, which also heads a real section, closed by a bare fence with no
// fence inside.
func swallowsProtected(body string, topLevel map[string]bool) bool {
	var open fence
	example, atStart := false, false
	for line := range strings.SplitSeq(body, "\n") {
		line = strings.TrimRight(line, "\r")
		if marker, ok := parseFence(line); ok {
			switch {
			case open.char == 0:
				open, atStart = marker, true
			case marker.closes(open):
				open, example = fence{}, false
			case example:
				return true
			}
			continue
		}
		heading := strings.TrimSpace(line)
		if strings.HasPrefix(heading, "## ") && (runtimeHeadings[heading] || isProtectedHeading(heading)) {
			if !open.info || !atStart || !topLevel[heading] {
				return true
			}
			example = true
		}
		if heading != "" {
			atStart = false
		}
	}
	return example
}

// cutInside returns at most limit bytes of text, ending between characters and
// closing a code block left open.
func cutInside(text string, limit int) string {
	prefix := runePrefix(text, limit)
	open := openFence(prefix)
	if open.char == 0 {
		return prefix
	}
	closer := "\n" + strings.Repeat(string(open.char), open.length)
	short := runePrefix(text, limit-len(closer))
	if openFence(short) != open {
		// The block's delimiter and its closer do not both fit.
		return cutOutsideFence(text, limit)
	}
	return short + closer
}

// openFence returns the delimiter of the code block text leaves open, or the
// zero fence.
func openFence(text string) fence {
	var open fence
	for line := range strings.SplitSeq(text, "\n") {
		if f, ok := parseFence(strings.TrimRight(line, "\r")); ok {
			switch {
			case open.char == 0:
				open = f
			case f.closes(open):
				open = fence{}
			}
		}
	}
	return open
}

// runePrefix returns the longest prefix of text of at most limit bytes that
// does not split a character.
func runePrefix(text string, limit int) string {
	if len(text) <= limit {
		return text
	}
	for limit > 0 && !utf8.RuneStart(text[limit]) {
		limit--
	}
	return text[:max(limit, 0)]
}

// cutOutsideFence returns the longest prefix of text, ending at a line break
// outside any fenced code block, that is at most limit bytes long. The text
// starts outside a fence, as every section does.
func cutOutsideFence(text string, limit int) string {
	if len(text) <= limit {
		return text
	}
	safe, offset := 0, 0
	var open fence
	for _, line := range strings.SplitAfter(text, "\n") {
		if offset+len(line) > limit || !strings.HasSuffix(line, "\n") {
			break
		}
		if f, ok := parseFence(strings.TrimRight(line, "\r\n")); ok {
			switch {
			case open.char == 0:
				open = f
			case f.closes(open):
				open = fence{}
			}
		}
		offset += len(line)
		if open.char == 0 {
			safe = offset
		}
	}
	return text[:safe]
}

const movedSectionsHeading = "\nMoved sections:\n\n"

func renderHistoryPointer(opts TaskCompaction, movedBytes int, moved []string) string {
	var b strings.Builder
	b.WriteString(TaskHistoryHeading + "\n\n")
	fmt.Fprintf(&b, "Sandman moved %d bytes of earlier Task content to `%s` to keep this Task near %d bytes. That file holds the complete Task as it was before. It is history: read it only when a detail you need is missing here and in the live repository, pull request and checks.\n", movedBytes, opts.ArchivePath, opts.Target)
	if len(moved) > 0 {
		b.WriteString(movedSectionsHeading)
		for _, heading := range moved {
			fmt.Fprintf(&b, "- %s\n", strings.TrimPrefix(heading, "## "))
		}
	}
	b.WriteString("\n" + taskHistoryEnd + "\n")
	return b.String()
}
